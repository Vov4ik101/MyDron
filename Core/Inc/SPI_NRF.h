#define DATA_SIZE				32					//(ищи в loop) Размер в байтах пакетов обмена данными (ПЕРЕДАТЧИК ДОЛЖЕН ПЕРЕДАВАТЬ РОВНО ТАКОЕ ЖЕ КОЛИЧЕСТВО БАЙТ!)
#define FREQ_CHANNEL			120					// Номер частотного канала. Всего 126 каналов. (ДОЛЖЕН БЫТЬ ОДИНАКОВ У ПРИЕМНИКА И ПЕРЕДАТЧИКА!)
#define TX_ADDRESS				0xE7E7E7E7E7		// Предустановленный адрес для передачи байт данных
#define RX_ADDRESS				0xC2C2C2C2C2		// 5-байтный адрес для приема данных (адрес для приема в канале 1)

//////////////////////////////////////////////////////////////////////////////////////
//					МАКРОСЫ ДЛЯ ЗАДАНИЯ АДРЕСОВ ПО УМОЛЧАНИЮ						//
