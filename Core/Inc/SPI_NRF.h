#define R_REGISTER				0x00				// Чтение регистра
#define W_REGISTER				0x20				// Запись регистра
#define R_RX_PAYLOAD			0x61				// Считывание из буфера принятых данных
#define W_TX_PAYLOAD			0xA0				// Запись в буфер отправляемых данных
#define FLUSH_TX				0xE1				// Очистка буфера передачи
#define FLUSH_RX				0xE2				// Очистка буфера приема
#define REUSE_TX_PL				0xE3				// Повторная отправка последних переданных данных
#define W_ACK_PAYLOAD			0xA8				// Отправка данных вместе с признаком подтверждения
#define W_TX_PAYLOAD_NOACK		0x60				// Отключение признака подтверждения в передающем пакете
#define NOP						0xFF				// Пустая команда


